/** shields.io escapes: "-" -> "--", "_" -> "__", space -> "_". */
export const shieldText = (s: string) => encodeURIComponent(s.replace(/-/g, "--").replace(/_/g, "__").replace(/ /g, "_"));

/** Logos on a light badge colour need dark text to stay readable. */
export function logoColor(hex: string) {
  const n = parseInt(hex, 16);
  const lum = (0.299 * ((n >> 16) & 255) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255)) / 255;
  return lum > 0.7 ? "black" : "white";
}
